const dictionaries: Record<Language, Dictionary> = { en, ar }

export function translate(language: Language, key: string, vars?: Record<string, string | number>) {
  const value = dictionaries[language][key] ?? dictionaries.en[key] ?? key
  if (!vars) return value
  return Object.entries(vars).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
    value
  )
}

export function useT() {
  const language = usePlatform((state) => state.settings?.language ?? "en")
  const t = React.useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(language, key, vars),
    [language]
  )
  return { t, language, dir: language === "ar" ? ("rtl" as const) : ("ltr" as const) }
}

export function useLanguageDirection() {
  const language = usePlatform((state) => state.settings?.language ?? "en")
  React.useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr"
  }, [language])
}
